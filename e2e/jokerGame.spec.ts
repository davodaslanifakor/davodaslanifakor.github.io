import { expect, test } from '@playwright/test'
test.setTimeout(90000)
for (const mode of ['keyboard', 'touch', 'motion'] as const) {
  const mobile = mode === 'touch'
  test(`adventure controls, pause and room return (${mode})`, async ({ page }) => {
    if (mobile) await page.setViewportSize({ width: 390, height: 844 })
    await page.emulateMedia({ reducedMotion: mode === 'motion' ? 'no-preference' : 'reduce' })
    await page.goto('/')
    await expect(page.locator('.room-page')).toHaveAttribute('data-ready', 'true')
    const trigger = page.locator('[data-object-id="bugjar"]')
    await trigger.press('Enter')
    const game = page.getByRole('region', { name: 'Joker’s great escape' })
    await expect(game).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
    await expect(page.getByRole('button', { name: 'Reset view', exact: true })).toBeHidden()
    await expect(page.getByRole('link', { name: 'Skip to CV', exact: true })).toBeVisible()
    await expect(game.getByRole('button', { name: 'Desk playground', exact: true })).toHaveCount(0)
    await game.getByRole('button', { name: 'Start adventure', exact: true }).click()
    await expect(game).toHaveAttribute('data-phase', 'walking')
    const grapple = page.getByRole('button', { name: /Grapple to the bookcase/ })
    if (mobile) {
      const bounds = await game.getByRole('button', { name: 'Right', exact: true }).boundingBox()
      await page.mouse.move(bounds!.x + 20, bounds!.y + 20); await page.mouse.down()
      await expect(grapple).toBeVisible({ timeout: 15000 }); await page.mouse.up()
    } else {
      await page.keyboard.down('KeyD'); await expect(grapple).toBeVisible({ timeout: 15000 }); await page.keyboard.up('KeyD')
    }
    await page.screenshot({ path: `docs/renders/joker-adventure/browser-${mobile ? 'mobile' : 'desk'}.png` })
    await page.getByRole('button', { name: /Grapple to the bookcase/ }).click()
    await expect(game).toHaveAttribute('data-phase', 'garage')
    await page.getByRole('button', { name: /Pull the book latch/ }).click()
    if (mode === 'motion') {
      await page.waitForTimeout(1500)
      await page.keyboard.press('KeyP')
      await expect(game).toHaveAttribute('data-phase', 'opening')
      await expect(game).toHaveAttribute('data-paused', 'true')
      await page.screenshot({ path: 'docs/renders/joker-adventure/latch-contact.png' })
      await page.keyboard.press('KeyP')
    }
    await expect(game).toHaveAttribute('data-phase', 'garage')
    await page.keyboard.down('KeyD'); await page.waitForTimeout(780); await page.keyboard.up('KeyD')
    await page.keyboard.down('KeyW'); await page.waitForTimeout(1050); await page.keyboard.up('KeyW')
    await expect(page.getByRole('button', { name: /Get into the car/ })).toBeVisible()
    await page.getByRole('button', { name: /Get into the car/ }).click()
    if (mode === 'motion') {
      await page.waitForTimeout(1900)
      await page.keyboard.press('KeyP')
      await expect(game).toHaveAttribute('data-phase', 'entering')
      await page.screenshot({ path: 'docs/renders/joker-adventure/door-contact.png' })
      await page.keyboard.press('KeyP')
      await page.waitForTimeout(2350)
      await page.keyboard.press('KeyP')
      await expect(game).toHaveAttribute('data-phase', 'entering')
      await page.screenshot({ path: 'docs/renders/joker-adventure/seated-contact.png' })
      await page.keyboard.press('KeyP')
    }
    await expect(game).toHaveAttribute('data-phase', 'driving', { timeout: 10000 })
    await game.getByRole('button', { name: /Get out/ }).click()
    await expect(game).toHaveAttribute('data-phase', 'garage')
    await page.getByRole('button', { name: /Get into the car/ }).click()
    await expect(game).toHaveAttribute('data-phase', 'driving', { timeout: 10000 })
    await game.getByRole('button', { name: 'Pause', exact: true }).click()
    await expect(game).toHaveAttribute('data-paused', 'true')
    await game.getByRole('button', { name: 'Resume', exact: true }).click()
    await expect(game).toHaveAttribute('data-paused', 'false')
    await game.getByRole('button', { name: /Change camera/ }).click()
    await expect(game).toHaveAttribute('data-view', 'cockpit')
    if (!mobile) {
      await page.setViewportSize({ width: 1180, height: 820 })
      await page.waitForTimeout(180)
      await expect(game).toHaveAttribute('data-ready', 'true')
      await expect(game).toHaveAttribute('data-view', 'cockpit')
    }
    await page.screenshot({ path: `docs/renders/joker-adventure/browser-${mobile ? 'mobile-' : ''}cockpit.png` })
    await expect(game).toHaveAttribute('data-free-play', 'false')
    await page.keyboard.down('KeyW'); await page.waitForTimeout(1000); await page.keyboard.up('KeyW')
    await page.keyboard.down('KeyB'); await page.waitForTimeout(200); await page.keyboard.up('KeyB')
    await expect(page.getByRole('button', { name: /Raise the lift/ })).toBeVisible()
    await page.getByRole('button', { name: /Raise the lift/ }).click()
    await expect(game).toHaveAttribute('data-phase', 'driving', { timeout: 10000 })
    await expect(game).toHaveAttribute('data-free-play', 'false')
    await page.keyboard.down('ShiftLeft'); await page.keyboard.down('KeyW')
    await game.getByRole('button', { name: /Jump to the desk/ }).waitFor({ state: 'visible', timeout: 10000 })
    await page.keyboard.press('Space')
    if (mode === 'motion') {
      // Continuing straight chooses the optional phone stunt.
      await expect(game).toHaveAttribute('data-phase', 'crashing', { timeout: 10000 })
      await page.keyboard.up('KeyW'); await page.keyboard.up('ShiftLeft')
      await expect(game).toHaveAttribute('data-phase', 'driving', { timeout: 10000 })
    } else {
      // Steer away from the phone in flight and brake onto the open desk.
      await page.keyboard.down('KeyD'); await page.waitForTimeout(600); await page.keyboard.up('KeyD')
      await page.keyboard.up('KeyW'); await page.keyboard.up('ShiftLeft')
      await page.keyboard.down('KeyB'); await page.waitForTimeout(600); await page.keyboard.up('KeyB')
    }
    await expect(game).toHaveAttribute('data-free-play', 'true', { timeout: 10000 })
    await expect(game).toHaveAttribute('data-phase', 'driving')
    await expect(game).toHaveAttribute('data-damaged', String(mode === 'motion'))
    await expect(game).toHaveAttribute('data-falls', '0')
    await page.screenshot({ path: `docs/renders/joker-adventure/landing-${mode}.png` })
    await game.getByRole('button', { name: /Get out/ }).click()
    await expect(game).toHaveAttribute('data-in-car', 'false')
    if (mobile) {
      const right = game.getByRole('button', { name: 'Right', exact: true })
      await expect(game.getByRole('button', { name: 'Run · Shift', exact: true })).toBeVisible()
      await right.focus(); await page.keyboard.down('Enter'); await page.waitForTimeout(350); await page.keyboard.up('Enter')
      await game.getByRole('button', { name: 'Jump · Space', exact: true }).click()
      await page.waitForTimeout(700)
      const left = game.getByRole('button', { name: 'Left', exact: true })
      await left.focus(); await page.keyboard.down('Enter'); await page.waitForTimeout(350); await page.keyboard.up('Enter')
    } else {
      await page.keyboard.down('ShiftLeft'); await page.keyboard.down('KeyD')
      await page.waitForTimeout(350); await page.keyboard.up('KeyD'); await page.keyboard.up('ShiftLeft')
      await page.keyboard.press('Space'); await page.waitForTimeout(700)
      await page.keyboard.down('ShiftLeft'); await page.keyboard.down('KeyA')
      await page.waitForTimeout(350); await page.keyboard.up('KeyA'); await page.keyboard.up('ShiftLeft')
    }
    await expect(game).toHaveAttribute('data-falls', '0')
    await page.screenshot({ path: `docs/renders/joker-adventure/free-foot-${mode}.png` })
    await page.getByRole('button', { name: /Get into the car/ }).click()
    await expect(game).toHaveAttribute('data-in-car', 'true', { timeout: 10000 })
    await page.keyboard.down('KeyS'); await page.waitForTimeout(180); await page.keyboard.up('KeyS')
    await page.keyboard.down('KeyB'); await page.waitForTimeout(200); await page.keyboard.up('KeyB')
    await expect(game).toHaveAttribute('data-phase', 'driving')
    await expect(game).toHaveAttribute('data-free-play', 'true')
    await expect(game).toHaveAttribute('data-falls', '0')
    await page.screenshot({ path: `docs/renders/joker-adventure/free-car-${mode}.png` })
    if (mode !== 'motion') {
      await page.keyboard.down('ShiftLeft')
      await expect(game).toHaveAttribute('data-boosting', 'true')
      await page.waitForTimeout(200)
      await page.screenshot({ path: `docs/renders/joker-adventure/nitro-${mode}.png` })
      await page.keyboard.up('ShiftLeft')
      await expect(game).toHaveAttribute('data-boosting', 'false')
      await page.keyboard.down('KeyS')
      await expect(game).toHaveAttribute('data-gliding', 'true', { timeout: 10000 })
      await page.waitForTimeout(250); await page.keyboard.up('KeyS')
      await game.getByRole('button', { name: 'Pause', exact: true }).click()
      await expect(game).toHaveAttribute('data-gliding', 'true')
      await page.screenshot({ path: `docs/renders/joker-adventure/umbrella-${mode}.png` })
      await game.getByRole('button', { name: 'Resume', exact: true }).click()
      await page.keyboard.down('KeyB')
      await expect(game).toHaveAttribute('data-on-floor', 'true', { timeout: 10000 })
      await page.keyboard.up('KeyB')
      await expect(game).toHaveAttribute('data-gliding', 'false')
      await expect(game).toHaveAttribute('data-falls', '0')
      await page.keyboard.press('Space')
      await page.keyboard.down('KeyS'); await page.waitForTimeout(650); await page.keyboard.up('KeyS')
      await page.keyboard.down('KeyB'); await page.waitForTimeout(350); await page.keyboard.up('KeyB')
      await expect(game).toHaveAttribute('data-falls', '0')
      await game.getByRole('button', { name: /Get out/ }).click()
      await expect(game).toHaveAttribute('data-in-car', 'false')
      await page.getByRole('button', { name: /Get into the car/ }).click()
      await expect(game).toHaveAttribute('data-in-car', 'true', { timeout: 10000 })
      await page.screenshot({ path: `docs/renders/joker-adventure/floor-${mode}.png` })
    }
    await game.getByRole('button', { name: 'Pause', exact: true }).click()
    await game.getByRole('button', { name: 'Start over', exact: true }).click()
    await expect(game).toHaveAttribute('data-phase', 'intro')
    await expect(game).toHaveAttribute('data-free-play', 'false')
    await page.keyboard.press('Escape')
    await expect(game).toBeHidden(); await expect(trigger).toBeFocused()
    await trigger.press('Enter'); await expect(game).toHaveAttribute('data-phase', 'intro')
    await game.getByRole('button', { name: /Back to the room/ }).click()
    await expect(trigger).toBeFocused()
  })
}
test('missing adventure asset offers retry and a working room exit', async ({ page }) => {
  await page.route('**/models/joker-adventure.glb', route => route.abort())
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.room-page')).toHaveAttribute('data-ready', 'true')
  await page.locator('[data-object-id="bugjar"]').press('Enter')
  const game = page.getByRole('region', { name: 'Joker’s great escape' })
  await expect(game.getByRole('status')).toContainText('could not load')
  await page.unroute('**/models/joker-adventure.glb')
  await game.getByRole('button', { name: 'Try again' }).click()
  await expect(game).toHaveAttribute('data-ready', 'true')
  await game.getByRole('button', { name: /Back to the room/ }).click()
  await expect(game).toBeHidden()
})
