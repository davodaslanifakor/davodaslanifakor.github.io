import { expect, test } from '@playwright/test'

test('portrait lens tracks the pointer, cycles filters, and closes on exit', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/studio/')
  const portrait = page.locator('.studio-portrait')
  const image = portrait.locator('.portrait-playground')
  await image.scrollIntoViewIfNeeded()
  await expect(portrait).toHaveAttribute('data-full-image', 'false')
  await image.hover({ position: { x: 120, y: 150 } })
  await expect.poll(() => image.evaluate(el => Number(el.style.getPropertyValue('--lens-radius')))).toBeGreaterThan(100)
  const before = await image.evaluate(el => el.style.getPropertyValue('--lens-x'))
  await image.hover({ position: { x: 240, y: 180 } })
  await expect.poll(() => image.evaluate(el => el.style.getPropertyValue('--lens-x'))).not.toBe(before)
  await image.click({ position: { x: 240, y: 180 } })
  await expect(portrait).toHaveAttribute('data-filter', 'duotone')
  await expect(portrait.getByRole('button', { name: 'Periwinkle', exact: true })).toHaveAttribute('aria-pressed', 'true')
  if (testInfo.project.name === 'chromium')
    await portrait.screenshot({ path: 'docs/renders/studio-projects/portrait-lens.png' })
  await page.mouse.move(10, 10)
  await expect.poll(() => image.evaluate(el => Number(el.style.getPropertyValue('--lens-radius')))).toBe(0)
  const mono = portrait.getByRole('button', { name: 'Monochrome', exact: true })
  await mono.focus()
  await page.keyboard.press('Enter')
  await expect(portrait).toHaveAttribute('data-filter', 'mono')
  await expect.poll(() => image.evaluate(el => Number(el.style.getPropertyValue('--lens-radius')))).toBeGreaterThan(100)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(portrait).toHaveAttribute('data-full-image', 'true')
  await expect(portrait.locator('.portrait-reveal')).toHaveCSS('filter', 'grayscale(1)')
})

