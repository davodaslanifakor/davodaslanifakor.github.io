test('portrait remains available without JavaScript', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, ...(baseURL ? { baseURL } : {}) })
  try {
    const page = await context.newPage()
    await page.goto('/studio/')
    const portrait = page.locator('.studio-portrait')
    await portrait.scrollIntoViewIfNeeded()
    await expect(portrait.locator('.portrait-base')).toBeVisible()
    await expect(portrait.locator('.portrait-base')).toHaveCSS('filter', 'none')
    await expect(portrait.locator('.portrait-filters')).toHaveCount(0)
  } finally { await context.close() }
})

test('touch devices can change filters without hover', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ hasTouch: true, viewport: { width: 390, height: 844 }, ...(baseURL ? { baseURL } : {}) })
  try {
    const page = await context.newPage()
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.goto('/studio/')
    const portrait = page.locator('.studio-portrait')
    await expect(portrait).toHaveAttribute('data-full-image', 'true')
    await portrait.getByRole('button', { name: 'Periwinkle', exact: true }).tap()
    await expect(portrait).toHaveAttribute('data-filter', 'duotone')
    await expect(portrait.locator('.portrait-reveal')).toHaveCSS('mask-image', 'none')
  } finally { await context.close() }
})

test('switching browser tabs clears the lens without revealing the full filter', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/studio/')
  const portrait = page.locator('.studio-portrait')
  const image = portrait.locator('.portrait-playground')
  await image.hover()
  await expect.poll(() => image.evaluate(el => Number(el.style.getPropertyValue('--lens-radius')))).toBeGreaterThan(100)
  await page.evaluate(() => {
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' })
    Object.defineProperty(document, 'hidden', { configurable: true, value: true })
    document.dispatchEvent(new Event('visibilitychange'))
    window.dispatchEvent(new Event('blur'))
  })
  await expect(portrait).toHaveAttribute('data-full-image', 'false')
  await expect.poll(() => image.evaluate(el => Number(el.style.getPropertyValue('--lens-radius')))).toBe(0)
  await page.evaluate(() => {
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'visible' })
    Object.defineProperty(document, 'hidden', { configurable: true, value: false })
    document.dispatchEvent(new Event('visibilitychange'))
    window.dispatchEvent(new Event('focus'))
    document.querySelector('.portrait-playground')?.dispatchEvent(new FocusEvent('focus'))
  })
  await expect(portrait).toHaveAttribute('data-full-image', 'false')
  await expect.poll(() => image.evaluate(el => Number(el.style.getPropertyValue('--lens-radius')))).toBe(0)
  await image.hover({ position: { x: 140, y: 140 } })
  await expect.poll(() => image.evaluate(el => Number(el.style.getPropertyValue('--lens-radius')))).toBeGreaterThan(100)
})
