# Where the orbit camera rests before the user focuses anything.
START_EYE = (-1.20, -2.05, 1.85)
START_TARGET = (0.25, 0.0, 1.05)


FOCUS_POINTS = []


def add_focus(object_id, eye, target):
    """A cam_<id> empty: position is the eye, -Z points at the object."""
    cam = empty(f"cam_{object_id}", location=eye)
    look_at(cam, target)
    FOCUS_POINTS.append((object_id, eye, target))
    return cam


def build_cameras():
    FOCUS_POINTS.clear()
    cams = [add_focus("start", START_EYE, START_TARGET)]
    cams.append(add_focus("monitor", (0.02, -0.48, 1.11), (0.02, 0.075, 0.94)))
    cams.append(add_focus("screen_left", (-0.40, -0.78, 1.20), (-0.41, 0.26, 1.12)))
    cams.append(add_focus("screen_right", (0.37, -0.76, 1.15), (0.37, 0.26, 1.07)))
    cams.append(add_focus("phone", (0.10, -0.82, 1.22), (0.64, -0.16, 0.88)))
    cams.append(add_focus("world_clocks", (0.0, -1.78, 1.84), (0.0, 0.390, 1.59)))
    cams.append(add_focus("speakers", (-0.47, -0.36, 0.94), (-0.47, 0.10, 0.80)))
    cams.append(add_focus("plush", (-0.47, -0.36, 0.98), (-0.47, 0.09, 0.90)))
    cams.append(add_focus("bugjar", (0.53, -0.32, 0.96), (0.53, 0.10, 0.89)))
    cams.append(add_focus("clock", (0.907, -0.24, 1.00), (0.907, 0.11, 0.86)))
    cams.append(add_focus("elephant", (0.41, -0.23, 0.88), (0.53, 0.015, 0.78)))
    for object_id, x in T.TOY_SLOTS.items():
        cams.append(add_focus(object_id, (x, -0.18, 0.823), (x, -0.043, 0.800)))
    return cams


def setup_lighting():
    """Warm key from the right, matching desk-wide-lit.jpg; screens light themselves."""
    import bpy
    key_data = bpy.data.lights.new("key", type='AREA')
    key_data.energy = 38.0
    key_data.size = 2.2
    key_data.color = (1.0, 0.94, 0.86)
    key = bpy.data.objects.new("static_light_key", key_data)
    key.location = (1.45, -1.05, 2.05)
    bpy.context.collection.objects.link(key)
    look_at(key, (0.1, 0.1, 0.9))

    fill_data = bpy.data.lights.new("fill", type='AREA')
    fill_data.energy = 12.0
    fill_data.size = 2.0
    fill_data.color = (0.82, 0.88, 1.0)
    fill = bpy.data.objects.new("static_light_fill", fill_data)
    fill.location = (-1.5, -1.4, 1.5)
    bpy.context.collection.objects.link(fill)
    look_at(fill, (0.0, 0.1, 0.9))

    world = bpy.data.worlds.new("world")
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs[0].default_value = (0.05, 0.05, 0.06, 1.0)
    world.node_tree.nodes["Background"].inputs[1].default_value = 1.1
    bpy.context.scene.world = world
    return [key, fill]


