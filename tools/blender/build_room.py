CAMERA_TS = os.path.join(REPO, "composables", "generated", "cameraFocus.ts")


def write_camera_focus():
    """Emit the focus points as TypeScript.

    Blender stays the single source of truth for camera placement; hand-editing
    them in two places is how they drift apart. Blender is Z-up and glTF is
    Y-up, so (x, y, z) becomes (x, z, -y) here, matching the exported GLB.
    """
    def to_gltf(v):
        return (round(v[0], 4), round(v[2], 4), round(-v[1], 4))

    lines = [
        "// Generated by tools/blender/build_room.py. Do not edit by hand.",
        "import { Vector3 } from 'three'",
        "import type { CameraFocusPoint } from '~/composables/useCameraRig'",
        "",
        "export const CAMERA_FOCUS_POINTS: readonly CameraFocusPoint[] = [",
    ]
    for object_id, eye, target in FOCUS_POINTS:
        ex, ey, ez = to_gltf(eye)
        tx, ty, tz = to_gltf(target)
        lines.append(
            f"  {{ name: 'cam_{object_id}', position: new Vector3({ex}, {ey}, {ez}), "
            f"target: new Vector3({tx}, {ty}, {tz}) }},"
        )
    lines += ["]", ""]
    os.makedirs(os.path.dirname(CAMERA_TS), exist_ok=True)
    with open(CAMERA_TS, "w") as handle:
        handle.write("\n".join(lines))
    return CAMERA_TS


def export():
    import bpy
    os.makedirs(os.path.dirname(OUT_GLB), exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=OUT_GLB,
        export_format='GLB',
        export_apply=True,          # bake modifiers so the runtime gets final geometry
        export_cameras=False,
        export_lights=False,
        export_yup=True,
    )
    return OUT_GLB


def preview(path, shot="start", lens=34.0, eye=None, target=None):
    """Render a still from a cam_ empty so any object can be checked, not just the wide shot.

    `eye`/`target` override the shot for review-only angles (front, side, rear)
    without adding production cameras.
    """
    import bpy
    cam_data = bpy.data.cameras.new("preview")
    cam_data.lens = lens
    cam = bpy.data.objects.new("preview_cam", cam_data)
    bpy.context.collection.objects.link(cam)
    source = bpy.data.objects.get(f"cam_{shot}")
    if source is None:
        raise SystemExit(f"no cam_{shot} empty in the scene")
    cam.location = source.location
    cam.rotation_euler = source.rotation_euler
    if eye is not None:
        cam.location = eye
        look_at(cam, target if target is not None else (0, 0, 0))
    bpy.context.scene.camera = cam

    scene = bpy.context.scene
    scene.render.engine = 'BLENDER_EEVEE'
    scene.render.resolution_x = 1400
    scene.render.resolution_y = 1050
    scene.render.filepath = path
    scene.render.image_settings.file_format = 'PNG'
    scene.view_settings.view_transform = 'Standard'
    bpy.ops.render.render(write_still=True)
    return path


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    build()
    if "--preview" in argv:
        out = argv[argv.index("--preview") + 1]
        shot = argv[argv.index("--shot") + 1] if "--shot" in argv else "start"
        lens = float(argv[argv.index("--lens") + 1]) if "--lens" in argv else 34.0
        def vec(flag):
            return tuple(float(v) for v in argv[argv.index(flag) + 1].split(",")) if flag in argv else None
        print("PREVIEW", preview(out, shot, lens, vec("--eye"), vec("--target")))
    else:
        glb = export()
        cameras = write_camera_focus()
        print("EXPORTED", glb, os.path.getsize(glb))
        print("CAMERAS", cameras, len(FOCUS_POINTS))


if __name__ == "__main__":
    main()
