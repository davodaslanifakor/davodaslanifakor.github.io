"""Outline the Studio phrases from portfolio.ts using the bundled OFL brand font.

Run with Python fonttools + brotli installed. No font tooling ships to the browser.
The SVG geometry is generated; editorial copy stays in content/portfolio.ts.
"""
from pathlib import Path
import json
import re
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parents[2]
source = (root / 'content/portfolio.ts').read_text()
phrases = re.findall(r"text\('([^']+)'\)", re.search(r'heroPhrases: \[(.*?)\]', source).group(1))
font = TTFont(root / 'public/fonts/bilbo-swash-caps-latin.woff2')
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
scale = 1000 / font['head'].unitsPerEm
records = []
for phrase in phrases:
    x = 30
    paths = []
    for character in phrase:
        name = cmap[ord(character)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 900)))
        path = pen.getCommands()
        if path:
            paths.append(path)
        x += font['hmtx'][name][0] * scale
    records.append({'paths': paths, 'width': round(x + 60)})
width = max(record['width'] for record in records)
result = {'viewBox': f'0 0 {width} 1300', 'width': width, 'phrases': records}
(root / 'content/studioLettering.ts').write_text(
    '// Generated by tools/typography/build_studio_lettering.py.\n'
    '// Bilbo Swash Caps, OFL: public/fonts/bilbo-swash-caps-OFL.txt.\n'
    'export const studioLettering = ' + json.dumps(result, separators=(',', ':')) + ' as const\n'
)
print('Generated', len(records), 'phrases;', width, '× 1300')
